#!/usr/bin/env node
/**
 * Renders Dr. Ines Vega's recordings (game/content/recordings.ts) with ElevenLabs
 * into public/voice/<id>.mp3 and writes libs/voiceManifest.ts, so `play` runs the
 * tape under its transcript. Commit both: the game never calls ElevenLabs for them.
 *
 *   npm run voice:render                 reads .env.local, renders every recording
 *   npm run voice:render -- --dry-run    prints the speech text, calls nothing
 *
 * Env: ELEVENLABS_API_KEY (required), ELEVENLABS_VOICE_ID, ELEVENLABS_RECORDING_MODEL_ID.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const FALLBACK_MODEL = "eleven_multilingual_v2";
const REQUEST_TIMEOUT_MS = 180_000;
const TAIL_MS = 250;

const jiti = createJiti(import.meta.url, { alias: { "@": ROOT } });
const text = await jiti.import("../libs/voiceText.ts");
const profile = await jiti.import("../libs/voiceProfile.ts");

function config() {
  const apiKey = process.env.ELEVENLABS_API_KEY?.trim();
  const voiceId = process.env.ELEVENLABS_VOICE_ID?.trim() || profile.DEFAULT_VOICE_ID;
  const modelId = process.env.ELEVENLABS_RECORDING_MODEL_ID?.trim() || profile.DEFAULT_RECORDING_MODEL;
  return { apiKey, voiceId, models: [...new Set([modelId, FALLBACK_MODEL])] };
}

async function requestSpeech({ apiKey, voiceId }, modelId, speech, withTimestamps) {
  const route = withTimestamps ? "/with-timestamps" : "";
  const url = `${profile.ELEVENLABS_API}/text-to-speech/${voiceId}${route}?output_format=${profile.RECORDING_OUTPUT_FORMAT}`;
  const response = await fetch(url, {
    method: "POST",
    headers: { "xi-api-key": apiKey, "Content-Type": "application/json", Accept: withTimestamps ? "application/json" : "audio/mpeg" },
    body: JSON.stringify({ text: speech, model_id: modelId, voice_settings: profile.TAPE_SETTINGS }),
    signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
  });
  if (!response.ok) {
    const detail = (await response.text()).slice(0, 240).replace(/\s+/g, " ");
    console.warn(`    ${modelId}${route || " (plain)"} → ${response.status} ${detail}`);
    return null;
  }
  if (!withTimestamps) return { audio: Buffer.from(await response.arrayBuffer()), alignment: null };
  const json = await response.json();
  if (typeof json.audio_base64 !== "string") return null;
  return { audio: Buffer.from(json.audio_base64, "base64"), alignment: json.alignment ?? null };
}

function durationOf({ audio, alignment }) {
  const ends = alignment?.character_end_times_seconds ?? [];
  if (ends.length > 0) return Math.round(Math.max(...ends) * 1000) + TAIL_MS;
  return Math.round((audio.length * 8) / profile.RECORDING_KBPS);
}

async function renderTake(settings, modelId, script) {
  return (await requestSpeech(settings, modelId, script.text, true)) ?? (await requestSpeech(settings, modelId, script.text, false));
}

async function render(settings, id) {
  const transcript = text.recordingTranscript(id);
  for (const modelId of settings.models) {
    const script = text.buildSpeechScript(transcript, profile.supportsAudioTags(modelId));
    const take = await renderTake(settings, modelId, script);
    if (!take) continue;
    const durationMs = durationOf(take);
    await writeFile(path.join(ROOT, "public", "voice", `${id}.mp3`), take.audio);
    const timing = take.alignment ? "timestamps" : "estimated cues";
    console.log(`  ${id}: ${modelId}, ${(durationMs / 1000).toFixed(1)}s, ${Math.round(take.audio.length / 1024)} KB, ${timing}`);
    return {
      src: `/voice/${id}.mp3`,
      durationMs,
      cuesMs: text.cuesFromAlignment(script, take.alignment, durationMs),
      transcriptHash: text.transcriptHash(transcript),
    };
  }
  throw new Error(`could not render ${id}; check the key, ELEVENLABS_VOICE_ID and your plan's model access`);
}

function manifestSource(tapes, settings) {
  return [
    "// Generated by scripts/voice-recordings.mjs (npm run voice:render). Do not edit by hand.",
    `// ElevenLabs voice ${settings.voiceId}, rendered ${new Date().toISOString().slice(0, 10)}.`,
    'import type { RecordingTapes } from "@/libs/voiceText";',
    "",
    `export const RECORDING_TAPES: RecordingTapes = ${JSON.stringify(tapes, null, 2)};`,
    "",
  ].join("\n");
}

function dryRun(settings) {
  for (const id of text.RECORDING_IDS) {
    const script = text.buildSpeechScript(text.recordingTranscript(id), profile.supportsAudioTags(settings.models[0]));
    console.log(`\n${id} (${settings.models[0]}, ${script.text.length} chars):\n${script.text}`);
  }
}

async function main() {
  const settings = config();
  if (process.argv.includes("--dry-run")) return dryRun(settings);
  if (!settings.apiKey) throw new Error("ELEVENLABS_API_KEY is not set (add it to .env.local)");
  await mkdir(path.join(ROOT, "public", "voice"), { recursive: true });
  console.log(`Rendering ${text.RECORDING_IDS.length} recordings with voice ${settings.voiceId}`);
  const entries = [];
  for (const id of text.RECORDING_IDS) entries.push([id, await render(settings, id)]);
  const tapes = Object.fromEntries(entries);
  await writeFile(path.join(ROOT, "libs", "voiceManifest.ts"), manifestSource(tapes, settings));
  console.log("Wrote public/voice/*.mp3 and libs/voiceManifest.ts");
}

main().catch((error) => {
  console.error(`voice:render failed: ${error instanceof Error ? error.message : error}`);
  process.exitCode = 1;
});
