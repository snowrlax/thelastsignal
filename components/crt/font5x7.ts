export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 8;

type Glyph = readonly (readonly boolean[])[];

const GLYPHS: Record<string, Glyph> = Object.fromEntries(
  Object.entries(RAW).map(([char, rows]) => [char, rows.split("|").map((row) => [...row].map((cell) => cell === "#"))]),
);

/** Returns the glyph for a character, falling back to its unaccented form, then "?". */
export function glyphFor(char: string): Glyph {
  if (GLYPHS[char]) return GLYPHS[char];
  const plain = char.normalize("NFD").replace(/[̀-ͯ]/g, "");
  if (GLYPHS[plain]) return GLYPHS[plain];
  const upper = plain.toUpperCase();
  return GLYPHS[upper] ?? GLYPHS["?"];
}
